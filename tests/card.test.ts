import { describe, expect, test } from 'vitest';
import { readdir, readFile } from 'node:fs/promises';
import { CARD_ICONS, cardHtml, gallery, newCard, parseCard, snippet, type ProjectCard } from '../src/card.ts';

const card: ProjectCard = {
	version: 1,
	repository: 'itsNikolay/obsidian-hovered-table-of-content',
	headline: 'Hovered Table of Content.',
	sub: 'The outline of any Obsidian note, one hover away.',
	cta: 'View on GitHub',
	owner: 'itsNikolay',
	icons: ['obsidian', 'typescript', 'plugin'],
	image: { x: 50, y: 50, zoom: 100, height: 57 },
};

describe('cardHtml', () => {
	test('shows the headline, subtitle, button, owner and art', () => {
		const html = cardHtml(card, 'art.png');
		expect(html).toContain('>Hovered Table of Content.<');
		expect(html).toContain('>The outline of any Obsidian note, one hover away.<');
		expect(html).toContain('>View on GitHub<');
		expect(html).toContain('>itsNikolay<');
		expect(html).toContain('src="art.png"');
	});

	test('draws the icons in order, separated by sparks', () => {
		const html = cardHtml(card, 'art.png');
		const labels = [...html.matchAll(/class="icon" [^>]*aria-label="([^"]+)"/g)].map((m) => m[1]);
		expect(labels).toEqual(['Obsidian', 'TypeScript', 'Plugin']);
		expect(html.match(/class="spark"/g)).toHaveLength(2);
	});

	test('applies the picture crop', () => {
		const html = cardHtml({ ...card, image: { x: 80, y: 10, zoom: 130, height: 60 } }, 'art.png');
		expect(html).toContain('--fx: 80%; --fy: 10%; --zoom: 1.3; --media: 60%');
	});

	test('is a single dark card with a light hairline that holds on white and on dark backgrounds', () => {
		const html = cardHtml(card, 'art.png');
		expect(html).toContain('--card: #191c22');
		expect(html).not.toContain('prefers-color-scheme');
		expect(html).toMatch(/\.ring \{[^}]*rgba\(255, ?255, ?255/);
	});

	test('embeds the font faces it is given', () => {
		expect(cardHtml(card, 'art.png', '@font-face { font-family: "X"; }')).toContain('@font-face { font-family: "X"; }');
	});

	test('escapes HTML', () => {
		const html = cardHtml({ ...card, headline: '<script>x</script>', owner: 'a & b' }, 'art.png');
		expect(html).not.toContain('<script>x');
		expect(html).toContain('&lt;script&gt;x&lt;/script&gt;');
		expect(html).toContain('a &amp; b');
	});
});

describe('snippet and gallery', () => {
	test('the snippet links the image in this repository to the project', () => {
		expect(snippet('hovered-toc', card)).toBe('<a href="https://github.com/itsNikolay/obsidian-hovered-table-of-content"><img src="https://raw.githubusercontent.com/itsNikolay/itsNikolay/main/cards/hovered-toc/card.png" width="250" alt="Hovered Table of Content — The outline of any Obsidian note, one hover away."></a>');
	});

	test('the gallery lists every card with its preview and snippet', () => {
		const md = gallery([{ slug: 'b', card: { ...card, headline: 'Beta.' } }, { slug: 'a', card }]);
		expect(md).toContain('<!-- Generated by npm run render. Do not edit by hand. -->');
		expect(md.indexOf('## Beta')).toBeLessThan(md.indexOf('## Hovered Table of Content'));
		expect(md).toContain('<img src="a/card.png" width="250"');
		expect(md).toContain(snippet('a', card));
	});
});

describe('newCard', () => {
	test('starts a valid card from owner/name', () => {
		const fresh = newCard('itsNikolay/my-cool_tool');
		expect(fresh.headline).toBe('My Cool Tool.');
		expect(fresh.owner).toBe('itsNikolay');
		expect(fresh.repository).toBe('itsNikolay/my-cool_tool');
		expect(() => parseCard(fresh)).not.toThrow();
	});

	test('rejects anything but owner/name', () => {
		expect(() => newCard('just-a-name')).toThrow(/owner\/name/);
	});
});

describe('parseCard', () => {
	test('accepts a valid card and the $schema hint', () => {
		expect(parseCard(card)).toEqual(card);
		expect(() => parseCard({ $schema: '../../schema/card.schema.json', ...card })).not.toThrow();
	});

	test('rejects a card that breaks the signature', () => {
		expect(() => parseCard({ ...card, version: 2 })).toThrow(/version/);
		expect(() => parseCard({ ...card, repository: 'no-slash' })).toThrow(/repository/);
		expect(() => parseCard({ ...card, headline: ' ' })).toThrow(/headline/);
		expect(() => parseCard({ ...card, icons: ['obsidian', 'cobol'] })).toThrow(/cobol/);
		expect(() => parseCard({ ...card, icons: ['obsidian', 'typescript', 'plugin', 'github'] })).toThrow(/icons/);
		expect(() => parseCard({ ...card, image: { ...card.image, height: 90 } })).toThrow(/height/);
		expect(() => parseCard({ ...card, image: { ...card.image, zoom: 50 } })).toThrow(/zoom/);
	});

	test('the JSON Schema agrees with the TypeScript signature', async () => {
		interface Schema { properties: Record<string, unknown> & { image: { properties: object }; icons: { items: { enum: string[] } } } }
		const schema = JSON.parse(await readFile('schema/card.schema.json', 'utf8')) as Schema;
		expect(Object.keys(schema.properties).filter((key) => key !== '$schema').sort()).toEqual(Object.keys(card).sort());
		expect(Object.keys(schema.properties.image.properties).sort()).toEqual(Object.keys(card.image).sort());
		expect(schema.properties.icons.items.enum).toEqual(Object.keys(CARD_ICONS));
	});

	test('every card in cards/ follows the signature', async () => {
		const slugs = (await readdir('cards', { withFileTypes: true })).filter((entry) => entry.isDirectory()).map((entry) => entry.name);
		expect(slugs.length).toBeGreaterThan(0);
		for (const slug of slugs) {
			const raw: unknown = JSON.parse(await readFile(`cards/${slug}/card.json`, 'utf8'));
			expect(() => parseCard(raw), slug).not.toThrow();
		}
	});
});
